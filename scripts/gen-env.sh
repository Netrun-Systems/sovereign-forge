#!/usr/bin/env bash
# Build a compose .env from compose/.env.example.
#
# For every variable NAME listed in the example file, the value is, in order:
#   1. what is already in the target file (re-runs never rotate secrets),
#   2. the same-named variable in your shell environment,
#   3. a built-in default for non-secret settings,
#   4. a freshly generated random value for secrets.
# The result is written with mode 0600. Only variable names are printed.
#
# usage: gen-env.sh [--example FILE] [--out FILE]
set -Eeuo pipefail
HERE="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
# shellcheck source=lib.sh
. "$HERE/lib.sh"

EXAMPLE="$HERE/../compose/.env.example"
OUT="$HERE/../compose/.env"
while [ $# -gt 0 ]; do
  case $1 in
    --example) EXAMPLE=$2; shift 2 ;;
    --out) OUT=$2; shift 2 ;;
    -h|--help) sed -n '2,13p' "$0"; exit 0 ;;
    *) die "unknown argument: $1" ;;
  esac
done
[ -r "$EXAMPLE" ] || die "example file not found: $EXAMPLE"
need openssl

rand() { openssl rand -hex "${1:-24}"; }

declare -A cur=()
if [ -f "$OUT" ]; then
  while IFS= read -r line; do
    case $line in ''|'#'*) continue ;; esac
    cur["${line%%=*}"]=${line#*=}
  done < "$OUT"
fi

declare -A val=()
mapfile -t names < <(grep -E '^[A-Z][A-Z0-9_]*=' "$EXAMPLE" | cut -d= -f1)

# Pass 1: explicit values (existing file first, then the environment).
for n in "${names[@]}"; do
  if [ -n "${cur[$n]:-}" ]; then val[$n]=${cur[$n]}
  elif [ -n "${!n:-}" ]; then val[$n]=${!n}
  else val[$n]=""
  fi
done

# Pass 2: defaults and derived values, in dependency order.
dflt() { [ -n "${val[$1]}" ] || val[$1]=$2; }
dflt CI_ENGINE forgejo
case ${val[CI_ENGINE]} in forgejo|jenkins) ;; *) die "CI_ENGINE must be forgejo or jenkins" ;; esac
dflt WITH_CADDY true
dflt FORGE_HOST localhost
dflt ADMIN_USER forgeadmin
if [ "${val[WITH_CADDY]}" = true ]; then
  [ -n "${val[ADMIN_EMAIL]}" ] || die "ADMIN_EMAIL is required when WITH_CADDY=true (ACME contact address)"
  [ "${val[FORGE_HOST]}" != localhost ] || die "set FORGE_HOST to a real DNS name when WITH_CADDY=true"
  dflt FORGE_ROOT_URL "https://${val[FORGE_HOST]}/"
else
  dflt ADMIN_EMAIL "${val[ADMIN_USER]}@localhost"
  dflt FORGE_ROOT_URL "http://${val[FORGE_HOST]}:3000/"
fi
dflt HTTP_BIND 127.0.0.1:3000
dflt SSH_PUBLIC_PORT 2222
if [ -z "${val[DATA_DIR]}" ]; then
  val[DATA_DIR]="$(cd "$(dirname "$OUT")" && pwd)/data"
fi
dflt POSTGRES_DB forgejo
dflt POSTGRES_USER forgejo
dflt RUNNER_NAME "$(hostname -s 2>/dev/null || echo host)-runner"
dflt RUNNER_LABELS "docker:docker://node:20-bookworm,ubuntu-latest:docker://node:20-bookworm"
if [ "${val[CI_ENGINE]}" = jenkins ]; then
  dflt COMPOSE_PROFILES jenkins
  dflt CADDYFILE Caddyfile.jenkins
  if [ "${val[WITH_CADDY]}" = true ]; then
    [ -n "${val[JENKINS_HOST]}" ] || die "JENKINS_HOST is required for CI_ENGINE=jenkins with Caddy"
  fi
else
  dflt COMPOSE_PROFILES actions
  dflt CADDYFILE Caddyfile.forgejo
fi
dflt JENKINS_HEAP 1g

# Pass 3: secrets.
[ -n "${val[POSTGRES_PASSWORD]}" ] || val[POSTGRES_PASSWORD]=$(rand 24)
[ -n "${val[FORGEJO_SECRET_KEY]}" ] || val[FORGEJO_SECRET_KEY]=$(rand 32)

umask 077
tmp=$(mktemp "${OUT}.XXXXXX")
{
  echo "# Generated by scripts/gen-env.sh. Contains secrets. Mode 0600. Never commit."
  for n in "${names[@]}"; do printf '%s=%s\n' "$n" "${val[$n]}"; done
} > "$tmp"
mv "$tmp" "$OUT"
chmod 600 "$OUT"
log INFO "wrote $OUT (${#names[@]} variables, CI_ENGINE=${val[CI_ENGINE]}, WITH_CADDY=${val[WITH_CADDY]})"
